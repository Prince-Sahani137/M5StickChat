#!/usr/bin/env python3
"""Write include/ollama_ca.h containing the ROOT certificate that signs a host's TLS chain.

    python3 tools/make_ca_header.py                 # ollama.com -> include/ollama_ca.h
    python3 tools/make_ca_header.py host out.h      # other host / output path

The firmware pins this root CA, so HTTPS is verified (not just encrypted). Needs `openssl`
on the PATH and a normal system CA store. Re-run it if ollama.com ever changes certificate
authority; the stick then reports a TLS error instead of silently trusting anyone.
"""
import glob
import os
import re
import subprocess
import sys

host = sys.argv[1] if len(sys.argv) > 1 else "ollama.com"
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "include", "ollama_ca.h")
PEM = re.compile(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", re.S)


def openssl(args, stdin=""):
    return subprocess.run(["openssl"] + args, input=stdin, capture_output=True, text=True, timeout=30)


def field(pem, flag):
    r = openssl(["x509", "-noout", flag], pem + "\n")
    return r.stdout.strip().split("=", 1)[-1].strip() if r.returncode == 0 else ""


# 1) the chain the server sends
res = openssl(["s_client", "-showcerts", "-servername", host, "-connect", f"{host}:443"])
chain = PEM.findall(res.stdout)
if not chain:
    sys.exit(f"Could not read a certificate chain from {host}:443 (is it reachable?)\n{res.stderr[-300:]}")

BUNDLES = ["/etc/ssl/certs/ca-certificates.crt", "/etc/pki/tls/certs/ca-bundle.crt",
           "/etc/ca-certificates/extracted/tls-ca-bundle.pem", "/etc/ssl/cert.pem"]


def find_in_store(subject, hash_flag_pem):
    """Return a self-signed trust anchor from the system store whose subject is `subject`."""
    h = openssl(["x509", "-noout", "-subject_hash"], hash_flag_pem + "\n").stdout.strip()
    if h:
        for path in sorted(glob.glob(f"/etc/ssl/certs/{h}.*")):
            m = PEM.search(open(path, errors="ignore").read())
            if m and field(m.group(0), "-subject") == subject:
                return m.group(0)
    for b in BUNDLES:
        if not os.path.exists(b):
            continue
        for pem in PEM.findall(open(b, errors="ignore").read()):
            if field(pem, "-subject") == subject and field(pem, "-issuer") == subject:
                return pem
    return None


def find_by_issuer(issuer, pem):
    h = openssl(["x509", "-noout", "-issuer_hash"], pem + "\n").stdout.strip()
    if h:
        for path in sorted(glob.glob(f"/etc/ssl/certs/{h}.*")):
            m = PEM.search(open(path, errors="ignore").read())
            if m and field(m.group(0), "-subject") == issuer:
                return m.group(0)
    for b in BUNDLES:
        if not os.path.exists(b):
            continue
        for p2 in PEM.findall(open(b, errors="ignore").read()):
            if field(p2, "-subject") == issuer:
                return p2
    return None


# 2) Walk the chain from the top. A certificate can be a *cross-signed* root (for example
#    "GTS Root R4" signed by "GlobalSign Root CA"); in that case the trust anchor we want is the
#    self-signed certificate with the same subject, which is in the system store.
root = None
print("Chain sent by the server:")
for i, pem in enumerate(chain):
    print(f"  [{i}] subject: {field(pem, '-subject')}\n      issuer:  {field(pem, '-issuer')}")
for pem in reversed(chain):
    subject, issuer = field(pem, "-subject"), field(pem, "-issuer")
    if subject == issuer:                      # server sent a self-signed root itself
        root = pem
    else:
        root = find_in_store(subject, pem) or find_by_issuer(issuer, pem)
    if root:
        break
if root is None:
    sys.exit("No trust anchor from this chain was found in the system trust store.\n"
             "Install/update your CA certificates (e.g. 'sudo apt install --reinstall ca-certificates') and retry.")

root_subject = field(root, "-subject")
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
with open(out, "w") as f:
    f.write(f"// Generated by tools/make_ca_header.py for {host}\n// Root CA: {root_subject}\n#pragma once\n")
    f.write('static const char OLLAMA_ROOT_CA[] = R"PEM(\n' + root.strip() + '\n)PEM";\n')
print(f"Wrote {os.path.normpath(out)}\nRoot CA: {root_subject}")
